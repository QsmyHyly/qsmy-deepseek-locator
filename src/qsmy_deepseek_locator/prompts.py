"""提示词：坐标口径的唯一来源。

这个模块承载本库最贵的一条经验：**坐标口径必须在提示词里写死，而且要写得自相矛盾都不行**。
参考项目的 A/B 实测（同一批 5 张合成图、15 个目标）：

    提示词版本                                   检出率      平均 IoU
    旧：只说「使用归一化值」、又说「无需考虑分辨率」   40% (6/15)  0.655
    新：显式换算公式 + 禁像素值 + 交代刻度不确定性    100% (15/15) 0.897

模型「看图 + 认颜色形状」的能力一直很强（标签准确率两版都是 100%），
失败几乎全部来自**坐标约定没被遵守**：它经常直接输出像素坐标。
所以改本文件的任何一句话，都必须重跑评测（qsmy-deepseek-locator bench）再下结论。

三条必须留在提示词里的说明（缺一条就会重新掉回那个坑）：

1. 模型拿不到、也推不出图片的真实分辨率 —— 图片在进模型前已被服务端缩放且不回传缩放后尺寸，
   它凭「看起来多大」脑补的数字（实测同一张图三次调用给出 1000x750 / 1000x800 / 1024x768）
   既不是原图尺寸也不是它眼前的栅格，不能写进输出、更不能拿来换算。
2. 它感知到的数值本身就是归一化数据 —— 对位置的感知天生是「相对整幅图的比例」，
   让它放心相信这个比例感，而不是先编一个尺寸再乘除。
3. 刻度不确定，但输出契约确定 —— 它分不清自己感知到的是 0~1 还是 0~1000（同一个位置差 1000 倍），
   所以立刻给死规则：统一按 0~1 输出，感知到 0~1000 就除以 1000。
   ⚠️ 只讲不确定性、不给规则，等于把上面那个 40% 的坑重新挖一遍。

另外小数位数刻意**不设上限**：只占画面宽度 0.4% 的小目标，宽度写成 3 位小数的 0.004
相对误差被放大 6.7%。代价是模型可能「编精度」，所以提示词里同时要求
「位数必须来自真实感知，宁可少写一位准的，也不要多写几位编的」。

@doc docs/API-NOTES.md#8-坐标口径为什么必须是-0010以及提示词有多要命
（该文档解决"为什么不能用像素坐标、提示词 A/B 的实测差距有多大"的问题；
改本文件的任何一句话之前请先读它。）
"""

from __future__ import annotations

# 全库唯一的坐标口径来源。locate() 与 bench 共用它；
# 单次调用可以用 system_prompt=... 覆盖，但请先读完本模块的说明再改。
DEFAULT_SYSTEM_PROMPT = (
    "你是一位物体定位助手。请根据用户需求识别图片中对应的内容，输出坐标及其中文名称。\n"
    "【坐标要求】所有坐标必须是 0.0~1.0 之间的小数（占宽/高的比例），禁止输出像素值。"
    "小数位数不设上限：能分辨多细就写多细（见下面的【精度】）。\n"
    "【你无法知道图片的实际分辨率】你既拿不到、也推不出这张图的真实像素尺寸：图片在送入你之前"
    "已被缩放，缩放后有多大不会告诉你。你凭「这张图看起来大概多大」猜出的任何数字"
    "（例如 1024x768、1000x1000）都只是臆测——它既不是原始尺寸，也不是你眼前这幅图的栅格，"
    "所以不要把它写进输出，更不要拿它当任何计算的依据。\n"
    "【你感知到的数值本身就是归一化数据】你对位置的感知天生是「相对整幅图的比例」而不是像素："
    "你看到或感觉到的那个数，描述的本来就是「这个点在整张图上占多大比例」，请直接相信它。"
    "唯一要留意的是刻度：你无法确定自己感知到的是 0~1 刻度（比例）还是 0~1000 刻度（千分比），"
    "两者描述的是同一个位置，只差 1000 倍。本项目统一按 0~1 输出：若你感觉到的是 0~1000 那一档"
    "（例如 350 表示 35%），除以 1000 后再写出来（350 -> 0.35）。"
    "两个刻度都允许带小数位：0~1000 档写 350.25 同样合法，它表示 35.025%，除以 1000 后写成 0.35025。\n"
    "换算方式：x = 像素x / 图片宽，y = 像素y / 图片高。\n"
    "【精度：能分辨多细就写多细，别提前抹平】小数位数没有上限，也不要为了整齐而强行凑成固定几位。"
    "只分辨到千分之一，写 0.351 就够；若能看得更细，就照实多写（0.3512、0.35125、0.351253 都合法）。"
    "小目标尤其要留意：一个只占画面宽度 0.4% 的小物件，宽度若写成 3 位小数的 0.004 就被放大了 6.7%，"
    "多写几位才留得住它真实的大小。"
    "但多出来的位数必须来自你真实的感知——不确定的末位不要凭感觉补数字凑数，"
    "宁可少写一位准的，也不要多写几位编的。\n"
    "例如某目标中心位于图片宽度的 35%、高度的 62% 处，就写 x=0.35，y=0.62；"
    "若看起来更靠左、约在 35.12% 处，就写 x=0.3512。\n"
    "请直接输出比例数值，不要输出像素值、不要输出你猜测的分辨率、不要解释换算过程。\n"
    "【输出格式】只输出一个 JSON 数组：\n"
    '[{"bbox_2d": [x1, y1, x2, y2], "label": "名称"}, {"point_2d": [x, y], "label": "名称"}]\n'
    "bbox_2d 为 [左上 x, 左上 y, 右下 x, 右下 y]，point_2d 为 [x, y]，均为 0.0~1.0 的小数（位数不限）。"
    "找不到目标时输出空数组 []。"
)

# 默认的用户消息（target 为空时用）。
DEFAULT_USER_PROMPT = "识别图中的主要物体，逐个输出中文名称与坐标。"


# 这些词开头的 target 自带「全部」的意思，句式里的「所有的」要省掉，
# 否则会拼出「请找出图中所有的所有物体」这种重复句（实测 deepseek-flash 仍能
# 正确理解，但措辞明显是坏的，而且暴露了句式写死这件事）。
_ALL_INCLUSIVE = ("所有", "全部", "每个", "各个", "一切", "整张", "整个", "全部")


def build_user_prompt(target: str | None = None) -> str:
    """把「找什么」拼成用户消息。

    Args:
        target: 目标描述，例如 "红色圆形"、"登录按钮"、"画面里的人"。
            为空则返回 DEFAULT_USER_PROMPT（= 识别主要物体）。
            以「所有 / 全部 / 每个」等量词开头时，句式不再叠加「所有的」。

    Returns:
        用户消息文本。注意这里**只描述找什么，不描述坐标怎么给** ——
        坐标口径归 system 消息（DEFAULT_SYSTEM_PROMPT），两处都写迟早会打架。
    """
    text = (target or "").strip()
    if not text:
        return DEFAULT_USER_PROMPT
    if text.startswith(_ALL_INCLUSIVE):
        return f"请找出图中的{text}，逐个输出中文名称与坐标。"
    return f"请找出图中所有的{text}，逐个输出中文名称与坐标。"


__all__ = ["DEFAULT_SYSTEM_PROMPT", "DEFAULT_USER_PROMPT", "build_user_prompt"]
